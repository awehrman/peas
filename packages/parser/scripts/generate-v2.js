#!/usr/bin/env node
/**
 * Compiles src/v2/grammar/ingredient-line.peggy into
 * src/v2/grammar/generated/parser.ts (gitignored). The output is plain
 * JavaScript wrapped as an unchecked TypeScript module so tsc and vitest can
 * consume it without a separate declaration file.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import peggy from "peggy";

const packageDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const grammarPath = join(packageDir, "src/v2/grammar/ingredient-line.peggy");
const outputPath = join(packageDir, "src/v2/grammar/generated/parser.ts");

export function generateV2Parser() {
  const source = peggy.generate(readFileSync(grammarPath, "utf8"), {
    output: "source",
    format: "es",
    allowedStartRules: ["IngredientLine"],
    grammarSource: "ingredient-line.peggy",
  });

  mkdirSync(dirname(outputPath), { recursive: true });
  writeFileSync(
    outputPath,
    `// @ts-nocheck\n// Generated by scripts/generate-v2.js from ingredient-line.peggy. Do not edit.\n${source}`
  );
  return outputPath;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  console.log(`Generated ${generateV2Parser()}`);
}
