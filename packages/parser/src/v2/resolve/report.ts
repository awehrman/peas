import type { ResolverContext } from "./context.js";
import {
  type IngredientLineResult,
  processIngredientLine,
} from "./process-line.js";
import type { MentionStatus, SegmentResolution } from "./resolve-segment.js";
import { RESOLVER_VERSION } from "./version.js";

/** A golden case scored by top-candidate concept: `expectedConcept` is compared with the candidate concept's canonical name as a slug ("Granny Smith apple" -> "granny-smith-apple"). */
export interface SemanticReportCase {
  id: string;
  input: string;
  expectedConcept: string | null;
}

export interface ResolutionReportInput {
  /** Where the snapshot came from ("fixtures/lexicon/snapshot.json", "database"). */
  source: string;
  lines: readonly string[];
  context: ResolverContext;
  semanticCases?: readonly SemanticReportCase[];
  thresholds?: readonly number[];
  topUnresolved?: number;
}

const STATUSES: readonly MentionStatus[] = [
  "AUTO_RESOLVED",
  "NEEDS_REVIEW",
  "UNRESOLVED",
];

export function conceptSlug(name: string): string {
  return name
    .toLowerCase()
    .replace(/[^\p{L}\p{N}]+/gu, "-")
    .replace(/^-|-$/g, "");
}

function percent(part: number, total: number): string {
  return total === 0 ? "n/a" : `${((part / total) * 100).toFixed(1)}%`;
}

function cell(text: string): string {
  return text.replace(/\|/g, "\\|");
}

function topScore(mention: SegmentResolution): number {
  return mention.resolution.candidates[0]?.score ?? 0;
}

function unresolvedPhrases(mention: SegmentResolution): string[] {
  const spans =
    mention.status === "UNRESOLVED"
      ? mention.resolution.unresolved
      : (mention.resolution.candidates[0]?.unresolved ?? []);
  return spans.map((span) => span.text.toLowerCase());
}

/**
 * Markdown report over a resolver context (Phase 3i): coverage by status, top unresolved phrases, ambiguous lexemes, semantic precision, and coverage/precision at score thresholds. Pure, so the parser script (fixture snapshot) and the database script (live snapshot) share it.
 *
 * Coverage at a threshold is the share of corpus mentions that are not UNRESOLVED and whose top score reaches it; precision is the share of semantic cases at or above it whose top concept is the expected one.
 */
export function buildResolutionReport(input: ResolutionReportInput): string {
  const {
    context,
    lines,
    semanticCases = [],
    thresholds = [0.5, 0.7, 0.9],
    topUnresolved = 25,
  } = input;
  const conceptName = (id: string | null | undefined) =>
    id ? (context.ontology.concept(id)?.canonicalName ?? id) : null;

  const results: IngredientLineResult[] = lines.map((line) =>
    processIngredientLine(line, context)
  );
  const mentions = results.flatMap((result) => result.mentions);

  const statusCounts: Record<MentionStatus, number> = {
    AUTO_RESOLVED: 0,
    NEEDS_REVIEW: 0,
    UNRESOLVED: 0,
  };
  const phraseCounts = new Map<string, number>();
  for (const mention of mentions) {
    statusCounts[mention.status] += 1;
    for (const phrase of unresolvedPhrases(mention))
      phraseCounts.set(phrase, (phraseCounts.get(phrase) ?? 0) + 1);
  }

  const entriesByText = new Map<string, Set<string>>();
  for (const entry of context.entries.values()) {
    const target = entry.conceptId
      ? `${entry.role} ${conceptName(entry.conceptId)}`
      : entry.attributeValueId
        ? `${entry.role} ${context.attributeValues.get(entry.attributeValueId)?.definitionKey ?? "?"}:${context.attributeValues.get(entry.attributeValueId)?.key ?? "?"}`
        : entry.preparationId
          ? `${entry.role} ${context.preparations.get(entry.preparationId)?.key ?? "?"}`
          : `${entry.role}${entry.valueKey ? ` ${entry.valueKey}` : ""}`;
    const key = entry.text.toLowerCase();
    const targets = entriesByText.get(key) ?? new Set<string>();
    targets.add(target);
    entriesByText.set(key, targets);
  }
  const ambiguous = [...entriesByText]
    .filter(([, targets]) => targets.size > 1)
    .sort(([a], [b]) => a.localeCompare(b));

  const semantic = semanticCases.map((semanticCase) => {
    const mention = processIngredientLine(semanticCase.input, context)
      .mentions[0];
    const top = mention?.resolution.candidates[0];
    const got = top ? conceptName(top.conceptId) : null;
    const correct =
      mention?.status === "UNRESOLVED"
        ? semanticCase.expectedConcept === null
        : got !== null && conceptSlug(got) === semanticCase.expectedConcept;
    return {
      semanticCase,
      status: mention?.status ?? "UNRESOLVED",
      score: top?.score ?? 0,
      got,
      correct,
    };
  });
  const correctCount = semantic.filter((row) => row.correct).length;

  const out: string[] = [];
  out.push("# Resolution report", "");
  out.push(
    `Generated by \`yarn evaluate:resolution\` (or \`db:evaluate:resolution\` for the live database). Resolver ${RESOLVER_VERSION}, lexicon revision ${context.revision}, snapshot from ${input.source}.`,
    ""
  );
  out.push(
    `${lines.length} lines, ${mentions.length} mentions, ${context.entries.size} lexicon entries.`,
    ""
  );

  out.push(
    "## Coverage by status",
    "",
    "| Status | Mentions | Share |",
    "| --- | ---: | ---: |"
  );
  for (const status of STATUSES)
    out.push(
      `| ${status} | ${statusCounts[status]} | ${percent(statusCounts[status], mentions.length)} |`
    );
  out.push("");

  out.push(`## Top unresolved phrases`, "");
  const phrases = [...phraseCounts]
    .sort(([a, countA], [b, countB]) => countB - countA || a.localeCompare(b))
    .slice(0, topUnresolved);
  if (phrases.length === 0) out.push("None.");
  else {
    out.push("| Phrase | Count |", "| --- | ---: |");
    for (const [phrase, count] of phrases)
      out.push(`| ${cell(phrase)} | ${count} |`);
  }
  out.push("");

  out.push(
    "## Ambiguous lexemes",
    "",
    "Entry text with more than one target. The resolver picks by role priority and applicability; each of these is worth a look.",
    ""
  );
  if (ambiguous.length === 0) out.push("None.");
  else {
    out.push("| Text | Targets |", "| --- | --- |");
    for (const [text, targets] of ambiguous)
      out.push(`| ${cell(text)} | ${cell([...targets].sort().join("; "))} |`);
  }
  out.push("");

  out.push("## Semantic precision", "");
  if (semantic.length === 0) out.push("No semantic cases.");
  else {
    out.push(
      `${correctCount} / ${semantic.length} correct (${percent(correctCount, semantic.length)}).`,
      ""
    );
    out.push(
      "| Case | Input | Expected | Got | Status | Score | |",
      "| --- | --- | --- | --- | --- | ---: | --- |"
    );
    for (const row of semantic) {
      out.push(
        `| ${row.semanticCase.id} | ${cell(row.semanticCase.input)} | ${row.semanticCase.expectedConcept ?? "(unresolved)"} | ${row.got ? cell(row.got) : "(none)"} | ${row.status} | ${row.score.toFixed(3)} | ${row.correct ? "✓" : "✗"} |`
      );
    }
  }
  out.push("");

  out.push(
    "## Coverage and precision by threshold",
    "",
    "| Threshold | Corpus coverage | Semantic cases at or above | Precision |",
    "| ---: | ---: | ---: | ---: |"
  );
  for (const threshold of thresholds) {
    const covered = mentions.filter(
      (mention) =>
        mention.status !== "UNRESOLVED" && topScore(mention) >= threshold
    ).length;
    const above = semantic.filter(
      (row) => row.status !== "UNRESOLVED" && row.score >= threshold
    );
    out.push(
      `| ${threshold} | ${percent(covered, mentions.length)} | ${above.length} | ${percent(above.filter((row) => row.correct).length, above.length)} |`
    );
  }
  out.push("");

  return out.join("\n");
}
